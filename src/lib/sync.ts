import type { ItemDTO, ItemFields } from './items.ts';
import { ITEM_LABELS } from './items.ts';
import type { RelationDTO } from './relations.ts';
import type { EventDTO } from './events.ts';
import type { ContextDTO } from './contexts.ts';

export type ItemDetailBundle = {
  item: ItemDTO;
  relations: { outgoing: RelationDTO[]; incoming: RelationDTO[] };
  events: EventDTO[];
};

export type ExportSource = {
  details: ItemDetailBundle[];
  contexts: (ContextDTO & { member_ids?: string[] })[];
  exportedAt?: string;
};

export type ExportArtifact = {
  filename: string;
  mime: string;
  content: string;
};

function fieldLines(fields: ItemFields): string[] {
  const lines: string[] = [];
  for (const [key, value] of Object.entries(fields)) {
    if (typeof value === 'string' && value.trim()) lines.push(`- ${key}: ${value.trim()}`);
  }
  return lines;
}

function provenanceLine(detail: ItemDetailBundle): string {
  const derived = detail.relations.outgoing.find((r) => r.kind === 'derived_from');
  const parts = [`origin: ${detail.item.origin}`];
  if (detail.item.source_label) parts.push(`source: ${detail.item.source_label}`);
  parts.push(derived ? `derived_from: ${derived.to_id}` : 'derived_from: none');
  return parts.join(' · ');
}

export function buildJsonExport(source: ExportSource): ExportArtifact {
  const payload = {
    format: 'gsc-export',
    version: 1,
    exported_at: source.exportedAt ?? new Date().toISOString(),
    items: source.details.map((d) => ({
      item: d.item,
      relations: d.relations,
      events: d.events,
    })),
    contexts: source.contexts,
  };
  return {
    filename: 'gsc-export.json',
    mime: 'application/json',
    content: JSON.stringify(payload, null, 2),
  };
}

export function buildMarkdownBundle(source: ExportSource): ExportArtifact {
  const at = source.exportedAt ?? new Date().toISOString();
  const lines: string[] = ['# GSC Bundle', '', `Exported: ${at}`, ''];
  lines.push(`- items: ${source.details.length}`);
  lines.push(`- contexts: ${source.contexts.length}`, '');
  lines.push('## Index', '');
  for (const d of source.details) {
    lines.push(`- [${d.item.title}](#${d.item.id}) · ${ITEM_LABELS[d.item.type]} · ${d.item.status}`);
  }
  lines.push('');
  for (const d of source.details) {
    const { item } = d;
    lines.push(`## ${item.title}`, '', `<a id="${item.id}"></a>`, '');
    lines.push(`- id: ${item.id}`);
    lines.push(`- type: ${item.type}`);
    lines.push(`- domain: ${item.domain}`);
    lines.push(`- status: ${item.status}`);
    lines.push(`- ${provenanceLine(d)}`);
    lines.push(`- created: ${item.created_at} · updated: ${item.updated_at}`, '');
    const fields = fieldLines(item.fields);
    if (fields.length) lines.push(...fields, '');
    if (d.relations.outgoing.length || d.relations.incoming.length) {
      lines.push('### Relations', '');
      for (const r of d.relations.outgoing) lines.push(`- ${r.kind} → ${r.to_id}${r.note ? ` (${r.note})` : ''}`);
      for (const r of d.relations.incoming) lines.push(`- ${r.kind} ← ${r.from_id}${r.note ? ` (${r.note})` : ''}`);
      lines.push('');
    }
    if (d.events.length) {
      lines.push('### History', '');
      for (const e of d.events) lines.push(`- ${e.at} · ${e.actor} · ${e.action} — ${e.detail}`);
      lines.push('');
    }
  }
  if (source.contexts.length) {
    lines.push('## Context views', '');
    for (const c of source.contexts) {
      lines.push(`### ${c.title}`, '');
      lines.push(`- id: ${c.id}`);
      lines.push(`- subject: ${c.subject}`);
      lines.push(`- scope: ${c.scope}`);
      lines.push(`- purpose: ${c.purpose}`);
      if (c.member_ids?.length) lines.push(`- members: ${c.member_ids.join(', ')}`);
      lines.push('');
    }
  }
  return { filename: 'gsc-bundle.md', mime: 'text/markdown', content: lines.join('\n') };
}

export function buildAgentContext(source: ExportSource): ExportArtifact {
  const at = source.exportedAt ?? new Date().toISOString();
  const objects = source.details.filter((d) => d.item.type.startsWith('object.'));
  const raws = source.details.filter((d) => d.item.type.startsWith('raw.'));
  const lines: string[] = [
    '# GSC Context',
    '',
    '> Generated by GSC Sync for agent CLIs (Claude Code / Codex).',
    '> Drop this file at the repository root (or append it to your agent context).',
    `> Exported: ${at} · ${source.details.length} items · ${source.contexts.length} context views.`,
    '',
    '## Structured objects',
    '',
  ];
  for (const d of objects) {
    const { item } = d;
    lines.push(`### ${item.title}`, '');
    lines.push(`- id: ${item.id}`);
    lines.push(`- type: ${item.type} (${ITEM_LABELS[item.type]})`);
    lines.push(`- status: ${item.status} · domain: ${item.domain}`);
    lines.push(`- ${provenanceLine(d)}`);
    for (const line of fieldLines(item.fields)) lines.push(line);
    for (const r of d.relations.outgoing) lines.push(`- ${r.kind} → ${r.to_id}`);
    for (const r of d.relations.incoming) lines.push(`- ${r.kind} ← ${r.from_id}`);
    lines.push('');
  }
  lines.push('## Raw information', '');
  for (const d of raws) {
    const { item } = d;
    lines.push(`### ${item.title}`, '');
    lines.push(`- id: ${item.id}`);
    lines.push(`- type: ${item.type} · status: ${item.status}`);
    lines.push(`- ${provenanceLine(d)}`);
    const content = typeof item.fields.content_text === 'string' ? item.fields.content_text.trim() : '';
    if (content) lines.push('', content, '');
  }
  if (source.contexts.length) {
    lines.push('## Context views', '');
    for (const c of source.contexts) {
      lines.push(`- **${c.title}** (${c.id}) — subject: ${c.subject}; purpose: ${c.purpose}`);
      if (c.member_ids?.length) {
        const titles = c.member_ids.map((id) => source.details.find((d) => d.item.id === id)?.item.title ?? id);
        lines.push(`  - members: ${titles.join(', ')}`);
      }
    }
    lines.push('');
  }
  return { filename: 'GSC-CONTEXT.md', mime: 'text/markdown', content: lines.join('\n') };
}

export function downloadArtifact(artifact: ExportArtifact): void {
  const blob = new Blob([artifact.content], { type: `${artifact.mime};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = artifact.filename;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  URL.revokeObjectURL(url);
}
